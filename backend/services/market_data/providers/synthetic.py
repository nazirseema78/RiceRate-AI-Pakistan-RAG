"""Synthetic demonstration provider: loads the fictional CSVs in data/synthetic.

All observations are labelled data_nature=synthetic and verification_status=synthetic_demo.
"""
from __future__ import annotations

import csv
from datetime import datetime
from pathlib import Path

from backend.config import get_settings
from backend.models.price import DataNature, PriceObservation, SourceMetadata, VerificationStatus
from backend.services.market_data.base import Availability, MarketDataProvider, ProviderResult


def _read(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


class SyntheticDemoProvider(MarketDataProvider):
    provider_key = "synthetic_demo"

    def __init__(self, directory: Path | None = None):
        self.directory = Path(directory or get_settings().synthetic_dir)

    def get_source_metadata(self) -> SourceMetadata:
        return SourceMetadata(
            provider_key=self.provider_key, name="RiceRate Synthetic Demo Data", url="",
            data_nature=DataNature.synthetic,
            description="Fictional demonstration prices, quotations and news generated by scripts/generate_synthetic_data.py. NOT real market data.",
            price_types=["wholesale", "export", "broker_quotation"], update_frequency="static (regenerate with script)",
            access_notes="Local files only.")

    def check_availability(self) -> Availability:
        f = self.directory / "synthetic_market_prices.csv"
        if not get_settings().load_synthetic_demo_data:
            return Availability(False, "disabled", "LOAD_SYNTHETIC_DEMO_DATA=false")
        return Availability(f.exists(), "available" if f.exists() else "unavailable",
                            "" if f.exists() else f"{f} not found - run scripts/generate_synthetic_data.py")

    def fetch_latest_prices(self) -> ProviderResult:
        res = ProviderResult(message="synthetic demo dataset")
        for r in _read(self.directory / "synthetic_market_prices.csv"):
            res.observations.append(PriceObservation(
                product_key=r["product_key"], product_name=r["product_name"], product_type=r["product_type"],
                variety=r["variety"], grade=r["grade"], market=r["market"], city=r["city"], province=r["province"],
                country=r["country"], price=float(r["price"]), currency=r["currency"], unit=r["unit"],
                price_category=r["price_category"], observed_at=datetime.fromisoformat(r["observed_at"]),
                source_name=r["source_name"], source_document=r["source_document"],
                verification_status=VerificationStatus.synthetic_demo, data_nature=DataNature.synthetic,
                notes="SYNTHETIC DEMONSTRATION DATA"))
        for q in _read(self.directory / "synthetic_broker_quotations.csv"):
            res.quotations.append({**q, "price": float(q["price"]), "quantity_mt": float(q["quantity_mt"] or 0),
                                   "source_name": "RiceRate Synthetic Demo Generator", "product_type":
                                   "broken_rice" if q["product_key"].startswith("broken") else "rice",
                                   "verification_status": VerificationStatus.synthetic_demo.value, "is_synthetic": True})
        for n in _read(self.directory / "synthetic_news_articles.csv"):
            res.news.append({**n, "is_synthetic": True})
        return res

    def fetch_historical_prices(self, start=None, end=None) -> ProviderResult:
        return self.fetch_latest_prices()  # the synthetic CSV already contains the full history
